use anchor_lang::prelude::*;
use solana_keccak_hasher::hashv;

use crate::errors::CumzillaraptorsError;

pub const METADATA_DOMAIN: &[u8] = b"CUMZILLARAPTORS_METADATA_V1";
pub const DEVNET_CLUSTER: &[u8] = b"devnet";
pub const MAX_METADATA_PROOF_LEN: usize = 9;
pub const MAX_NAME_BYTES: usize = 64;
pub const MAX_URI_BYTES: usize = 128;
/// Immutable devnet commitment generated from the reviewed 420-URI artifact.
pub const APPROVED_METADATA_ROOT: [u8; 32] = [0x58, 0x56, 0x06, 0xc4, 0x39, 0x63, 0x58, 0xe0, 0x47, 0xf8, 0x70, 0x2d, 0x85, 0x65, 0x48, 0x58, 0x7e, 0xb0, 0xa1, 0x8b, 0xc3, 0x8b, 0xe1, 0x07, 0x6b, 0x0e, 0x4e, 0xa7, 0xf1, 0x5a, 0xc0, 0x19];

fn is_canonical_ar_uri(uri: &str) -> bool {
    matches!(
        uri.strip_prefix("ar://"),
        Some(tx_id)
            if tx_id.len() == 43
                && !uri.to_ascii_lowercase().contains("placeholder")
                && tx_id
                    .bytes()
                    .all(|byte| byte.is_ascii_alphanumeric() || byte == b'_' || byte == b'-')
    )
}

pub fn metadata_leaf_v1(
    program_id: &Pubkey,
    nft_id: u16,
    name: &str,
    uri: &str,
) -> Result<[u8; 32]> {
    let canonical_name = format!("cumzillaraptor #{nft_id}");
    require!(
        (1..=420).contains(&nft_id)
            && name == canonical_name
            && name.len() <= MAX_NAME_BYTES
            && uri.len() <= MAX_URI_BYTES
            && is_canonical_ar_uri(uri),
        CumzillaraptorsError::InvalidMetadataProof
    );
    let cluster_len = u8::try_from(DEVNET_CLUSTER.len())
        .map_err(|_| error!(CumzillaraptorsError::InvalidMetadataProof))?;
    let name_len = u16::try_from(name.len())
        .map_err(|_| error!(CumzillaraptorsError::InvalidMetadataProof))?;
    let uri_len =
        u16::try_from(uri.len()).map_err(|_| error!(CumzillaraptorsError::InvalidMetadataProof))?;
    Ok(hashv(&[
        METADATA_DOMAIN,
        program_id.as_ref(),
        &[cluster_len],
        DEVNET_CLUSTER,
        &nft_id.to_be_bytes(),
        &name_len.to_be_bytes(),
        name.as_bytes(),
        &uri_len.to_be_bytes(),
        uri.as_bytes(),
    ])
    .to_bytes())
}

pub fn verify_metadata_proof(
    program_id: &Pubkey,
    root: &[u8; 32],
    nft_id: u16,
    name: &str,
    uri: &str,
    proof: &[[u8; 32]],
) -> Result<()> {
    require!(
        proof.len() <= MAX_METADATA_PROOF_LEN,
        CumzillaraptorsError::ProofTooLong
    );
    let leaf = metadata_leaf_v1(program_id, nft_id, name, uri)?;
    let computed = proof.iter().fold(leaf, |current, sibling| {
        if current <= *sibling {
            hashv(&[&current, sibling]).to_bytes()
        } else {
            hashv(&[sibling, &current]).to_bytes()
        }
    });
    require!(
        computed == *root,
        CumzillaraptorsError::InvalidMetadataProof
    );
    Ok(())
}

